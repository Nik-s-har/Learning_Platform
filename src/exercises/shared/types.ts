/**
 * Общие типы для всех движков упражнений.
 * Движки не знают о предметной области (глаголы, буквы, слова) —
 * данные готовит адаптер конкретного тренажёра или курса.
 */

export interface ExerciseResult {
  /** Сколько заданий выполнено верно. */
  score: number;
  /** Сколько заданий было всего. */
  total: number;
  /** Сколько времени заняло прохождение, мс. Есть не у всех упражнений. */
  durationMs?: number;
}

export interface BaseExerciseProps {
  /** Заголовок над игровым полем. */
  title?: string;
  /** Пояснение под заголовком. */
  instruction?: string;
  /** Вызывается один раз, когда упражнение полностью пройдено. */
  onFinish?: (result: ExerciseResult) => void;
}

/** Состояние строки обратной связи под игровым полем. */
export type FeedbackState = 'idle' | 'good' | 'bad';
